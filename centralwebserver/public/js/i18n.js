export function detectInitialLocale() {
    try {
        const params = new URLSearchParams(window.location.search);
        const qLang = params.get('lang')?.toLowerCase();
        if (qLang === 'en' || qLang === 'de') {
            return qLang;
        }
        const saved = window.localStorage.getItem('ironlock_lang')?.toLowerCase();
        if (saved === 'en' || saved === 'de') {
            return saved;
        }
        const nav = (navigator.language || 'de').toLowerCase();
        if (nav.startsWith('en')) {
            return 'en';
        }
    }
    catch {
        // Fallback to German
    }
    return 'de';
}
export function t(lang, key) {
    return UI_STRINGS[lang]?.[key] ?? UI_STRINGS.de[key] ?? key;
}
export function applyStaticDomTranslations(lang) {
    document.documentElement.lang = lang;
    document.title = t(lang, 'page_title');
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            el.textContent = t(lang, key);
        }
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
        const key = el.getAttribute('data-i18n-html');
        if (key) {
            el.innerHTML = t(lang, key);
        }
    });
    document
        .querySelectorAll('[data-i18n-placeholder]')
        .forEach((el) => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) {
            el.placeholder = t(lang, key);
        }
    });
    const btnDe = document.getElementById('btn-lang-de');
    const btnEn = document.getElementById('btn-lang-en');
    if (btnDe && btnEn) {
        btnDe.classList.toggle('lang-btn-active', lang === 'de');
        btnDe.setAttribute('aria-pressed', String(lang === 'de'));
        btnEn.classList.toggle('lang-btn-active', lang === 'en');
        btnEn.setAttribute('aria-pressed', String(lang === 'en'));
    }
}
