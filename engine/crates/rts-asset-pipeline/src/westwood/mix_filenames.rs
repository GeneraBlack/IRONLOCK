/// Extracts embedded ASCII filenames from an XCC `"local mix database.dat"` payload
/// (supports Olaf van der Spek's 52-byte `"XCC by Olaf van der Spek"` header as well as
/// plain NUL-delimited or newline-delimited filename lists).
pub fn parse_xcc_local_mix_database(db_bytes: &[u8]) -> Vec<String> {
    if db_bytes.is_empty() {
        return Vec::new();
    }

    let start_offset = if db_bytes.len() >= 52 && db_bytes.starts_with(b"XCC by Olaf van der Spek")
    {
        52usize
    } else {
        0usize
    };

    let mut names = Vec::new();
    let mut cur = Vec::new();
    for &b in &db_bytes[start_offset..] {
        if b == 0 || b == b'\n' || b == b'\r' {
            if !cur.is_empty() {
                if let Ok(s) = std::str::from_utf8(&cur) {
                    let trimmed = s.trim();
                    if trimmed.len() >= 3
                        && trimmed.len() <= 64
                        && trimmed.contains('.')
                        && trimmed.bytes().all(|c| c.is_ascii_graphic() || c == b' ')
                    {
                        names.push(trimmed.to_string());
                    }
                }
                cur.clear();
            }
        } else {
            cur.push(b);
        }
    }
    if !cur.is_empty() {
        if let Ok(s) = std::str::from_utf8(&cur) {
            let trimmed = s.trim();
            if trimmed.len() >= 3
                && trimmed.len() <= 64
                && trimmed.contains('.')
                && trimmed.bytes().all(|c| c.is_ascii_graphic() || c == b' ')
            {
                names.push(trimmed.to_string());
            }
        }
    }
    names
}
