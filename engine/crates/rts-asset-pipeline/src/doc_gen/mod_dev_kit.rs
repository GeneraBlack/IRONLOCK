/// Writes the generated Mod Development Kit Markdown reference to `output_path`.
pub fn write_mod_dev_kit_markdown(output_path: &Path) -> Result<()> {
    if let Some(parent) = output_path.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent).with_context(|| {
                format!("Failed to create parent directory {}", parent.display())
            })?;
        }
    }
    let md = generate_mod_dev_kit_markdown();
    fs::write(output_path, md)
        .with_context(|| format!("Failed to write documentation to {}", output_path.display()))
}
