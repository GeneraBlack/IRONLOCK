/// Renders a deterministic `taplo.toml` file mapping all 14 TOML catalog globs to `<schema_dir_prefix>/<file>`.
pub fn render_taplo_toml(schema_dir_prefix: &str, entries: &[CatalogSchemaEntry]) -> String {
    let prefix = schema_dir_prefix.trim_matches('/');
    let mut out = String::from(
        "# Auto-generated by rts-asset-pipeline (schemars + Taplo TOML autocomplete)\n",
    );
    for entry in entries {
        out.push_str("\n[[rule]]\n");
        let quoted_globs: Vec<String> = entry
            .taplo_globs
            .iter()
            .map(|g| format!("\"{g}\""))
            .collect();
        out.push_str(&format!("include = [{}]\n", quoted_globs.join(", ")));
        let rel_schema = if prefix.is_empty() {
            entry.schema_filename.to_string()
        } else {
            format!("{prefix}/{}", entry.schema_filename)
        };
        out.push_str(&format!("schema = {{ path = \"{rel_schema}\" }}\n"));
    }
    out
}

/// Generates all 14 auto-derived `.schema.json` files and `taplo.toml` inside `output_dir`.
pub fn generate_json_schemas_and_taplo(output_dir: &Path) -> Result<Vec<PathBuf>> {
    fs::create_dir_all(output_dir)
        .with_context(|| format!("Failed to create schema directory {}", output_dir.display()))?;

    let entries = build_all_catalog_schemas()?;
    let mut written = Vec::with_capacity(entries.len() + 1);

    for entry in &entries {
        let p = output_dir.join(entry.schema_filename);
        let mut pretty = serde_json::to_string_pretty(&entry.json_value)?;
        pretty.push('\n');
        fs::write(&p, pretty).with_context(|| format!("Failed to write {}", p.display()))?;
        written.push(p);
    }

    let taplo_content = render_taplo_toml("schemas", &entries);
    let taplo_path = output_dir.join("taplo.toml");
    fs::write(&taplo_path, taplo_content)
        .with_context(|| format!("Failed to write {}", taplo_path.display()))?;
    written.push(taplo_path);

    Ok(written)
}

fn default_reference_md_path_for_mod(mod_path: &Path) -> PathBuf {
    let cwd_docs = Path::new("docs");
    if cwd_docs.is_dir() {
        return cwd_docs.join("MOD_SCHEMA_REFERENCE.md");
    }
    if let Some(parent) = mod_path.parent() {
        let sibling_docs = parent.join("docs");
        if sibling_docs.is_dir() {
            return sibling_docs.join("MOD_SCHEMA_REFERENCE.md");
        }
    }
    PathBuf::from("docs/MOD_SCHEMA_REFERENCE.md")
}

/// Executes `gen-docs --mod-path <mod_path>`:
/// 1. Writes all 14 auto-derived `schemars` JSON Schemas into `<mod_path>/schemas/*.schema.json`.
/// 2. Writes `<mod_path>/taplo.toml` pointing to `schemas/*.schema.json`.
/// 3. Writes `docs/MOD_SCHEMA_REFERENCE.md` (or `reference_md_override` when supplied).
pub fn generate_mod_docs_and_schemas(
    mod_path: &Path,
    reference_md_override: Option<&Path>,
) -> Result<GenDocsReport> {
    let schemas_dir = mod_path.join("schemas");
    fs::create_dir_all(&schemas_dir)
        .with_context(|| format!("Failed to create {}", schemas_dir.display()))?;

    let entries = build_all_catalog_schemas()?;
    let mut schema_files = Vec::with_capacity(entries.len());

    for entry in &entries {
        let schema_path = schemas_dir.join(entry.schema_filename);
        let mut pretty = serde_json::to_string_pretty(&entry.json_value)?;
        pretty.push('\n');
        fs::write(&schema_path, pretty)
            .with_context(|| format!("Failed to write {}", schema_path.display()))?;
        schema_files.push(schema_path);
    }

    let taplo_path = mod_path.join("taplo.toml");
    let taplo_content = render_taplo_toml("schemas", &entries);
    fs::write(&taplo_path, taplo_content)
        .with_context(|| format!("Failed to write {}", taplo_path.display()))?;

    let reference_markdown_path = reference_md_override
        .map(PathBuf::from)
        .unwrap_or_else(|| default_reference_md_path_for_mod(mod_path));
    write_mod_schema_reference_markdown(&reference_markdown_path, &entries)?;

    Ok(GenDocsReport {
        schema_files,
        taplo_path,
        reference_markdown_path,
    })
}

