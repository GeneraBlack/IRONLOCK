/// Metadata and auto-derived `schemars` JSON Schema for a single SDK TOML catalog.
#[derive(Debug, Clone)]
pub struct CatalogSchemaEntry {
    pub slug: &'static str,
    pub schema_filename: &'static str,
    pub rust_type: &'static str,
    pub description: &'static str,
    pub taplo_globs: &'static [&'static str],
    pub root_schema: RootSchema,
    pub json_value: Value,
}

/// Summary of files generated by `generate_mod_docs_and_schemas` (`gen-docs --mod-path <mod>`).
#[derive(Debug, Clone)]
pub struct GenDocsReport {
    pub schema_files: Vec<PathBuf>,
    pub taplo_path: PathBuf,
    pub reference_markdown_path: PathBuf,
}

fn make_entry(
    slug: &'static str,
    schema_filename: &'static str,
    rust_type: &'static str,
    description: &'static str,
    taplo_globs: &'static [&'static str],
    root_schema: RootSchema,
) -> Result<CatalogSchemaEntry> {
    let mut json_value = serde_json::to_value(&root_schema)
        .with_context(|| format!("Failed to serialize RootSchema for {rust_type}"))?;
    if let Some(obj) = json_value.as_object_mut() {
        obj.entry("$schema".to_string()).or_insert_with(|| {
            Value::String("http://json-schema.org/draft-07/schema#".to_string())
        });
        obj.insert("title".to_string(), Value::String(rust_type.to_string()));
    }
    Ok(CatalogSchemaEntry {
        slug,
        schema_filename,
        rust_type,
        description,
        taplo_globs,
        root_schema,
        json_value,
    })
}

